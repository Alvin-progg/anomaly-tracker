"use client";

import { useActionState } from "react";
import { verifyOtpAction, type OtpFormState } from "@/app/lib/auth/actions";

const initialState: OtpFormState = {};

interface Enrolment {
  /** SVG markup, or a data: URI, depending on the GoTrue version. */
  qrCode: string;
  secret: string;
}

function QrCode({ qrCode }: { qrCode: string }) {
  if (qrCode.startsWith("data:")) {
    // eslint-disable-next-line @next/next/no-img-element -- a data: URI from our own auth server, not a remote asset
    return <img src={qrCode} alt="Two-factor authentication QR code" width={180} height={180} />;
  }
  // Raw SVG generated by our own GoTrue instance and never by user input.
  return <div className="w-[180px] h-[180px] [&>svg]:w-full [&>svg]:h-full" dangerouslySetInnerHTML={{ __html: qrCode }} />;
}

export function VerifyForm({ enrolment }: { enrolment?: Enrolment }) {
  const [state, formAction, isPending] = useActionState(verifyOtpAction, initialState);

  return (
    <div className="min-h-screen flex items-center justify-center bg-gradient-to-br from-[#1F3864] via-[#2E74B5] to-[#1F3864] relative overflow-hidden px-4">
      <div className="absolute inset-0 bg-dot-grid pointer-events-none" />

      <div className="relative w-full max-w-[420px] bg-white rounded-xl px-10 pt-10 pb-9 shadow-2xl">
        <div className="flex flex-col items-center mb-7">
          <div className="w-16 h-16 rounded-2xl bg-gradient-to-br from-[#1F3864] to-[#2E74B5] flex items-center justify-center mb-3.5 shadow-lg">
            <svg width="32" height="32" viewBox="0 0 24 24" fill="none" stroke="white" strokeWidth={2}>
              <rect x="3" y="11" width="18" height="11" rx="2" />
              <path d="M7 11V7a5 5 0 0 1 10 0v4" />
            </svg>
          </div>
          <div className="text-[22px] font-extrabold text-[#1F3864] tracking-tight">
            {enrolment ? "Set Up Two-Factor" : "Two-Factor Authentication"}
          </div>
          <div className="text-xs text-[#6B7A99] mt-0.5 text-center">
            {enrolment
              ? "Scan this code with your authenticator app, then enter the 6-digit code it shows."
              : "Enter the 6-digit code from your authenticator app."}
          </div>
        </div>

        {enrolment && (
          <div className="mb-5 flex flex-col items-center gap-3">
            <div className="p-3 bg-white border border-[#D1D9E6] rounded-lg">
              <QrCode qrCode={enrolment.qrCode} />
            </div>
            <div className="w-full">
              <div className="text-[11px] text-[#6B7A99] mb-1">Can&apos;t scan? Enter this key manually:</div>
              <div className="px-3 py-2 bg-[#F5F7FA] border border-[#D1D9E6] rounded-md text-xs font-mono text-[#1A2033] break-all select-all">
                {enrolment.secret}
              </div>
            </div>
          </div>
        )}

        <form action={formAction} className="flex flex-col gap-3.5">
          <div>
            <label htmlFor="code" className="block text-xs font-semibold text-gray-700 mb-1.5">
              Verification Code
            </label>
            <input
              id="code"
              name="code"
              type="text"
              inputMode="numeric"
              autoComplete="one-time-code"
              maxLength={6}
              placeholder="000000"
              autoFocus
              className="w-full px-3.5 py-2.5 border-[1.5px] border-[#D1D9E6] rounded-lg text-sm text-[#1A2033] tracking-[0.4em] text-center outline-none focus:border-[#2E74B5] transition-colors"
            />
          </div>

          {state?.error && (
            <div className="px-3 py-2 bg-red-100 rounded-md text-xs text-red-800 border border-red-200">
              {state.error}
            </div>
          )}

          <button
            type="submit"
            disabled={isPending}
            className="mt-1 py-2.75 bg-[#1F3864] disabled:bg-[#6B7A99] disabled:cursor-not-allowed text-white rounded-lg text-sm font-bold tracking-wide transition-colors"
          >
            {isPending ? "Verifying..." : "Verify"}
          </button>
        </form>

        <div className="mt-4 text-center">
          <a href="/login" className="text-xs text-[#2E74B5] font-medium">
            Back to sign in
          </a>
        </div>
      </div>
    </div>
  );
}
